import {build} from 'esbuild';
import {mkdir,cp,rm,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
const output=process.argv[2] ?? 'dist';
if(process.argv.length>3 || path.resolve(output)===path.resolve('.'))throw Error('Pass only a dedicated build output directory');
await mkdir(output,{recursive:true});
await build({entryPoints:['routing/plugin.js'],outfile:path.join(output,'index.js'),bundle:true,platform:'node',format:'esm',target:'node22'});
if(output==='dist')await rm('dist/runway',{recursive:true,force:true});
await cp('runway',path.join(output,'runway'),{recursive:true,filter:p=>!p.includes('__pycache__')});
await cp('runway_main.py',path.join(output,'runway_main.py'));
await cp('routing/WORKFLOW.md',path.join(output,'WORKFLOW.md'));
await writeFile(path.join(output,'package.json'),JSON.stringify({name:'chief-runway-opencode',version:'0.1.0',type:'module',main:'index.js'},null,2));
await writeFile(path.join(output,'THIRD_PARTY_NOTICES.md'),'Zod (MIT)\n\n'+await readFile('node_modules/zod/LICENSE','utf8'));
