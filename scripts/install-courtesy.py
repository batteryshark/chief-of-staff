#!/usr/bin/env python3
"""Strict THREE-leaf helper: never invokes the broad kit installers.

Review/export the source first. --skill-sha256 pins generated bytes;
--source-pin verifies the narrow helper/input bundle SHA-256, not a Git label.
This CLI deliberately requires an explicit canonical HOME and explicit mode.
"""
import argparse
import json
from pathlib import Path
from courtesy import skill, target
from courtesy_owned import OwnedSkills, digest, LEDGER, source_pin


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('mode', choices=['dry-run', 'install', 'rollback'])
    p.add_argument('--home', required=True)
    p.add_argument('--source-pin', required=True)
    p.add_argument('--skill-sha256', required=True)
    p.add_argument('--run', help='exact install run ID, required for rollback')
    args = p.parse_args()
    text = skill()
    if source_pin() != args.source_pin:
        p.error('helper/input bundle does not match reviewed source pin')
    if digest(text.encode()) != args.skill_sha256:
        p.error('generated skill does not match reviewed SHA-256')
    if args.mode == 'rollback' and not args.run:
        p.error('rollback requires --run')
    outputs = {target(Path(args.home), h): text for h in ('opencode', 'claude', 'codex')}
    owned = OwnedSkills(args.home, outputs, rollback=args.mode == 'rollback')
    if args.mode == 'install':
        print('run=' + owned.install())
    elif args.mode == 'rollback':
        owned.rollback(args.run)
    else:
        print(json.dumps(dict(source_pin=args.source_pin, sha256=args.skill_sha256,
                              leaves=[str(p) for p in outputs], ledger=LEDGER), indent=2))


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise SystemExit(str(e))
